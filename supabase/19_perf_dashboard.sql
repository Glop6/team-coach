-- ---------------------------------------------------------------------
-- Funciones de permisos (leen los roles de Team Coach; un acceso desactivado no ve nada)
-- ---------------------------------------------------------------------
create or replace function perf.my_role() returns text
language sql stable security definer set search_path = '' as $$
  select case pr.role when 'admin' then 'owner' when 'lead' then 'lead' when 'member' then 'contractor' end
  from public.profiles pr where pr.id = auth.uid() and not pr.disabled
$$;

create or replace function perf.current_app_role() returns text
language sql stable security definer set search_path = '' as $$ select perf.my_role() $$;

create or replace function perf.is_owner() returns boolean
language sql stable security definer set search_path = '' as $$ select coalesce(perf.my_role() = 'owner', false) $$;

create or replace function perf.is_lead_or_owner() returns boolean
language sql stable security definer set search_path = '' as $$ select coalesce(perf.my_role() in ('owner', 'lead'), false) $$;

create or replace function perf.current_person_id() returns uuid
language sql stable security definer set search_path = '' as $$
  select x.id from perf.people x
  join public.profiles pr on pr.id = auth.uid() and not pr.disabled
  where x.tc_user_id = pr.id or (pr.person_id is not null and x.tc_person_id = pr.person_id)
  limit 1
$$;

create or replace function perf.can_upload() returns boolean
language sql stable security definer set search_path = '' as $$
  select perf.is_owner()
      or (perf.my_role() is not null and exists (select 1 from perf.uploaders u where u.user_id = auth.uid()))
$$;

-- ¿Puedo ver los datos de esta persona del dashboard?
create or replace function perf.can_see_person(p uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select p is not null and (
    perf.is_owner()
    or p = perf.current_person_id()
    or (perf.my_role() = 'lead' and exists (
          select 1 from perf.people x
          join public.people tp on tp.id = x.tc_person_id
          where x.id = p and x.active and tp.group_id in (select public.my_group_ids())))
  )
$$;

-- ---------------------------------------------------------------------
-- Funciones del dashboard (mismos nombres que hoy, para cambiar lo mínimo)
-- ---------------------------------------------------------------------
create or replace function perf.bump_data_epoch() returns bigint
language sql security definer set search_path = '' as $$
  update perf.data_epoch set epoch = epoch + 1 where id = 1 and perf.can_upload() returning epoch
$$;

create or replace function perf.clear_all_data() returns void
language plpgsql security definer set search_path = '' set statement_timeout = '120s' as $$
begin
  if not perf.is_owner() then raise exception 'Solo el admin puede borrar todos los datos'; end if;
  truncate perf.records, perf.qa_records, perf.upload_batches restart identity;
  perform perf.bump_data_epoch();
end $$;

create or replace function perf.delete_records_by_keys(keys text[]) returns integer
language plpgsql set search_path = '' set statement_timeout = '120s' as $$
declare n integer;
begin
  with d as (delete from perf.records
             where dedup_hash = any(array(select md5(k)::uuid from unnest(keys) k)) returning 1)
  select count(*)::int into n from d;
  if n > 0 then perform perf.bump_data_epoch(); end if;
  return n;
end $$;

create or replace function perf.delete_qa_by_keys(keys text[]) returns integer
language plpgsql set search_path = '' set statement_timeout = '120s' as $$
declare n integer;
begin
  with d as (delete from perf.qa_records where dedup_key = any(keys) returning 1)
  select count(*)::int into n from d;
  if n > 0 then perform perf.bump_data_epoch(); end if;   -- hoy no avisaba el cambio: el cache quedaba viejo
  return n;
end $$;

create or replace function perf.undo_import_batch(batch text) returns void
language plpgsql set search_path = '' set statement_timeout = '120s' as $$
begin
  if not perf.can_upload() then raise exception 'No tienes permiso para deshacer importaciones'; end if;
  delete from perf.records        where import_batch_id = batch;
  delete from perf.qa_records     where import_batch_id = batch;
  delete from perf.upload_batches where batch_id = batch;
  perform perf.bump_data_epoch();
end $$;

-- LOE manual: solo admin y quienes pueden subir datos (decisión 2026-10-28)
create or replace function perf.set_record_manual(p_key text, p_loe numeric, p_ok boolean) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not perf.can_upload() then raise exception 'Not allowed to edit this record'; end if;
  if p_loe is not null and p_loe < 0 then raise exception 'LOE must be 0 or more'; end if;
  update perf.records
     set loe_manual = p_loe, loe_ok = coalesce(p_ok, false),
         manual_by = perf.current_person_id(), manual_at = now()
   where dedup_hash = md5(p_key)::uuid;
  if not found then raise exception 'Record not found'; end if;
end $$;

create or replace function perf.touch_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end $$;

drop trigger if exists records_touch on perf.records;
create trigger records_touch before update on perf.records for each row execute function perf.touch_updated_at();
drop trigger if exists qa_touch on perf.qa_records;
create trigger qa_touch before update on perf.qa_records for each row execute function perf.touch_updated_at();

