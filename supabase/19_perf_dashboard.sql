create table if not exists perf.people (
  id            uuid primary key default gen_random_uuid(),
  full_name     text not null,
  email         text unique check (email = lower(email)),
  active        boolean not null default true,       -- false = ex-miembro (se ve marcado como inactivo)
  name_keys     text[] not null default '{}',        -- variantes del nombre en los Excel
  tc_person_id  uuid unique references public.people(id) on delete set null,  -- ficha en Team Coach
  tc_user_id    uuid unique references auth.users(id) on delete set null,     -- login sin ficha (el admin)
  created_at    timestamptz not null default now()
);

create table if not exists perf.uploaders (          -- quién puede subir datos (además del admin)
  user_id uuid primary key references auth.users(id) on delete cascade
);

create table if not exists perf.upload_batches (
  id          bigint generated by default as identity primary key,
  uploaded_by uuid references perf.people(id) on delete set null,
  file_name   text not null,
  file_type   text,
  period      text,
  row_count   integer,
  created_at  timestamptz not null default now(),
  batch_id    text,
  sheet_name  text,
  excluded    integer
);

create table if not exists perf.records (
  id              bigint generated by default as identity primary key,
  batch_id        bigint references perf.upload_batches(id) on delete cascade,
  person_id       uuid references perf.people(id) on delete set null,
  owner_raw       text,                              -- nombre tal como viene del Excel (permite deshacer vínculos)
  project         text,
  work_type       text,
  case_id         text,
  title           text,
  event_date      timestamptz,
  loe             numeric,
  system          text,
  source_file     text,
  extra           jsonb not null default '{}',
  dedup_key       text,
  import_batch_id text,
  dedup_hash      uuid generated always as (md5(dedup_key)::uuid) stored,
  updated_at      timestamptz not null default now(),
  loe_manual      numeric,
  loe_ok          boolean not null default false,
  manual_by       uuid references perf.people(id) on delete set null,
  manual_at       timestamptz
);

create table if not exists perf.qa_records (
  id              bigint generated by default as identity primary key,
  batch_id        bigint references perf.upload_batches(id) on delete cascade,
  person_id       uuid references perf.people(id) on delete set null,
  owner_raw       text,
  case_id         text,
  qa_status       text,
  reviewer        text,
  date_completed  timestamptz,
  secondary_date  timestamptz,
  fix_comment     text,
  follow_up_level integer,
  is_na           boolean not null default false,
  extra           jsonb not null default '{}',
  dedup_key       text,
  import_batch_id text,
  dedup_hash      uuid generated always as (md5(dedup_key)::uuid) stored,
  updated_at      timestamptz not null default now()
);

create table if not exists perf.qa_categories (
  dedup_key    text primary key,
  category     text not null,
  generated_at timestamptz not null default now(),
  generated_by uuid references perf.people(id) on delete set null
);

create table if not exists perf.app_settings (
  key        text primary key,
  value      jsonb not null,
  updated_by uuid references perf.people(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists perf.data_epoch (
  id    integer primary key default 1 check (id = 1),
  epoch bigint not null default 1
);
insert into perf.data_epoch (id, epoch) values (1, 1) on conflict (id) do nothing;

create table if not exists perf.ai_usage (
  id            bigint generated by default as identity primary key,
  person_id     uuid references perf.people(id) on delete set null,
  feature       text not null,
  model         text,
  input_tokens  integer,
  output_tokens integer,
  cost_usd      numeric,                             -- para el tope de costo de la IA
  created_at    timestamptz not null default now()
