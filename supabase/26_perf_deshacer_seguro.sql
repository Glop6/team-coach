-- =====================================================================
--  TEAM COACH · Cambio 37: "Deshacer subida" sin borrar el historial
--  Va DESPUÉS de 25_bamboo_fin_semana.sql y ANTES de publicar el dashboard de este cambio.
--  Antes: al subir de nuevo un archivo (por ejemplo, uno que trae todos los meses), las filas que ya
--  existían quedaban marcadas con la carga nueva, y "Deshacer" las borraba junto con lo nuevo.
--  Ahora:
--   1. El dashboard ya no vuelve a escribir las filas que no cambiaron: conservan su carga original.
--   2. Antes de modificar o reemplazar una fila guardada, el dashboard pide guardar su versión anterior
--      en perf.import_undo (perf.guardar_version_previa).
--   3. perf.undo_import_batch borra lo que esa carga agregó o modificó y restaura las versiones anteriores.
--      Si otra carga posterior ya volvió a cambiar esa fila, se deja la versión más nueva.
--  Re-ejecutable.
-- =====================================================================

create table if not exists perf.import_undo (
  id         bigint generated by default as identity primary key,
  batch_id   text not null,                                   -- la carga que modificó o reemplazó la fila
  tabla      text not null check (tabla in ('records', 'qa_records')),
  dedup_key  text not null,
  fila       jsonb not null,                                  -- la fila tal como estaba antes de esa carga
  created_at timestamptz not null default now(),
  unique (batch_id, tabla, dedup_key)
);
create index if not exists import_undo_batch_idx on perf.import_undo (batch_id);

alter table perf.import_undo enable row level security;
drop policy if exists import_undo_rw on perf.import_undo;
create policy import_undo_rw on perf.import_undo for all to authenticated
  using ((select perf.can_upload())) with check ((select perf.can_upload()));
revoke all on perf.import_undo from public, anon;
grant select, insert, delete on perf.import_undo to authenticated;
grant all on perf.import_undo to service_role;
grant usage, select on sequence perf.import_undo_id_seq to authenticated;

-- Guarda la versión actual de las filas indicadas antes de que la carga p_batch las cambie o las borre.
-- Si la misma carga la pide dos veces, queda la primera (la de antes de la carga).
create or replace function perf.guardar_version_previa(p_batch text, p_tabla text, p_keys text[]) returns integer
language plpgsql set search_path = '' set statement_timeout = '120s' as $$
declare n integer;
begin
  if not perf.can_upload() then raise exception 'No tienes permiso para subir datos'; end if;
  if p_tabla not in ('records', 'qa_records') then raise exception 'Tabla no válida: %', p_tabla; end if;
  execute format(
    'insert into perf.import_undo (batch_id, tabla, dedup_key, fila)
       select $1, %L, t.dedup_key, to_jsonb(t) - ''id'' - ''dedup_hash''
         from perf.%I t
        where t.dedup_hash = any(array(select md5(k)::uuid from unnest($2) k))
       on conflict (batch_id, tabla, dedup_key) do nothing', p_tabla, p_tabla)
  using p_batch, p_keys;
  get diagnostics n = row_count;
  return n;
end $$;

-- Devuelve void antes; ahora devuelve cuántas filas se borraron y cuántas se restauraron.
drop function if exists perf.undo_import_batch(text);
create function perf.undo_import_batch(batch text) returns jsonb
language plpgsql set search_path = '' set statement_timeout = '120s' as $$
declare
  n_rec integer; n_qa integer; r_rec integer := 0; r_qa integer := 0;
  t text; cols text; n integer;
begin
  if not perf.can_upload() then raise exception 'No tienes permiso para deshacer importaciones'; end if;
  delete from perf.records        where import_batch_id = batch;  get diagnostics n_rec = row_count;
  delete from perf.qa_records     where import_batch_id = batch;  get diagnostics n_qa  = row_count;
  foreach t in array array['records', 'qa_records'] loop
    -- todas las columnas que se pueden escribir (sin id ni las calculadas), así no hay que mantener una lista
    select string_agg(quote_ident(column_name), ', ' order by ordinal_position) into cols
      from information_schema.columns
     where table_schema = 'perf' and table_name = t and is_generated = 'NEVER' and column_name not in ('id', 'updated_at');
    execute format(
      'insert into perf.%I (%s, updated_at)
         select %s, now()
           from perf.import_undo u, jsonb_populate_record(null::perf.%I, u.fila) p
          where u.batch_id = $1 and u.tabla = %L
          order by u.id
       on conflict (dedup_hash) do nothing',
      t, cols, (select string_agg('p.' || c, ', ') from unnest(string_to_array(cols, ', ')) c), t, t)
    using batch;
    get diagnostics n = row_count;
    if t = 'records' then r_rec := n; else r_qa := n; end if;
  end loop;
  delete from perf.import_undo    where batch_id = batch;
  delete from perf.upload_batches where batch_id = batch;
  perform perf.bump_data_epoch();
  return jsonb_build_object('borrados', n_rec + n_qa, 'restaurados', r_rec + r_qa,
                            'casos_borrados', n_rec, 'casos_restaurados', r_rec,
                            'qa_borrados', n_qa, 'qa_restaurados', r_qa);
end $$;

revoke all on function perf.guardar_version_previa(text, text, text[]), perf.undo_import_batch(text) from public, anon;
grant execute on function perf.guardar_version_previa(text, text, text[]), perf.undo_import_batch(text) to authenticated, service_role;
